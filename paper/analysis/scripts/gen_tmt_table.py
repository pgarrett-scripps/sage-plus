#!/usr/bin/env python3
"""Write the HYpro16 TMT ratio-compression table (PXD020815)."""
from __future__ import annotations

from pathlib import Path

from _assets import record
from _tmt import TMT_INPUTS, load

HERE = Path(__file__).resolve().parent
PAPER = HERE.parent.parent
OUT = PAPER / "si" / "tmt_table.typ"
HEADER = f"// AUTO-GENERATED by scripts/{Path(__file__).name} -- do not edit by hand.\n"
ORDER = ("upstream-hrms2-mzml", "plus-b13-hrms2-mzml", "plus-b13-hrms2-raw",
         "upstream-sps-mzml", "plus-b13-sps-mzml", "plus-b13-sps-raw")


def cell(text: str, *, bold: bool = False) -> str:
    for ch in ("\\", "[", "]", "#", "$", "*", "_", "@", "<", ">"):
        text = text.replace(ch, "\\" + ch)
    weight = ', weight: "bold"' if bold else ""
    return f"[#text(size: 6.7pt{weight})[{text}]]"


def main() -> int:
    summary = load()
    published = summary["settings"]["paper"]
    lines = [
        HEADER,
        "#table(\n",
        "  columns: 9,\n",
        "  align: (left, left, left, right, right, right, right, right, right),\n",
        "  inset: 3pt,\n",
        "  table.header(\n",
        "    " + ", ".join(cell(label, bold=True) for label in (
            "Engine", "Method", "Input", "Quant PSMs", "Yeast peptides",
            "Fold 20:1", "Published", "Slope", "Missing",
        )) + ",\n",
        "  ),\n",
    ]
    for name in ORDER:
        row = summary["runs"][name]
        job = row["job"]
        values = (
            "Sage" if job["engine"] == "upstream" else "Sage Plus",
            "hrMS2" if job["method"] == "hrms2" else "SPS-MS3",
            "mzML" if job["input"] == "mzml" else "Thermo RAW",
            f'{row["quantified"]["all"]["psms"]:,}',
            f'{row["yeast_peptides_in_ratio_analysis"]:,}',
            f'{row["levels"]["1/20"]["observed_fold_1x_over_level"]:.3f}',
            f'{published[job["method"]]["1/20"]:.2f}',
            f'{row["compression_slope_spiked_levels"]:.3f}',
            f'{100 * row["missing_channels"]["all_species_excl_126"]:.2f}%',
        )
        lines.append("    " + ", ".join(cell(value) for value in values) + ",\n")
    lines.append(")\n")
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("".join(lines))
    record(
        "tbl.tmt",
        str(OUT.relative_to(PAPER)),
        kind="table",
        inputs=TMT_INPUTS,
        desc="HYpro16 TMT ratio compression for Sage and Sage Plus.",
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
