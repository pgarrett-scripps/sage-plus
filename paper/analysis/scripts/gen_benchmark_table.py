#!/usr/bin/env python3
"""Write the paired benchmark summary table from the committed CSV."""
from __future__ import annotations

import csv
from pathlib import Path
from statistics import median

from _assets import record

HERE = Path(__file__).resolve().parent
SRC = HERE / "benchmark_results.csv"
RELEASE_SRC = HERE / "release_comparison_results.csv"
SAGE_SRC = HERE / "sage_vs_plus_results.csv"
PAPER = HERE.parent.parent          # analysis/scripts/ -> analysis/ -> paper/
OUT = PAPER / "si" / "benchmark_table.typ"
RELEASE_OUT = PAPER / "si" / "release_comparison_table.typ"

HEADER = f"// AUTO-GENERATED by scripts/{Path(__file__).name} -- do not edit by hand.\n"


def cell(text: str, *, bold: bool = False) -> str:
    """Escape a value for Typst content and wrap it in brackets."""
    for ch in ("\\", "[", "]", "#", "$", "*", "_", "@", "<", ">"):
        text = text.replace(ch, "\\" + ch)
    weight = ', weight: "bold"' if bold else ""
    return f"[#text(size: 6.8pt{weight})[{text}]]"


def percent_change(candidate: str, baseline: str) -> float:
    return (float(candidate) / float(baseline) - 1) * 100


def main() -> int:
    with SRC.open(newline="") as fh:
        rows = list(csv.DictReader(fh))
    lines = [
        HEADER,
        "#table(\n",
        "  columns: 6,\n",
        "  align: (left, right, right, right, right, left),\n",
        "  inset: 3pt,\n",
        "  table.header(\n",
        "    " + ", ".join(cell(label, bold=True) for label in (
            "Workload", "Base wall", "New wall", "Wall change", "RSS change", "Output check"
        )) + ",\n",
        "  ),\n",
    ]
    for row in rows:
        values = (
            row["suite"],
            f'{float(row["baseline_wall_seconds"]):.2f} s',
            f'{float(row["candidate_wall_seconds"]):.2f} s',
            f'{percent_change(row["candidate_wall_seconds"], row["baseline_wall_seconds"]):+.1f}%',
            f'{percent_change(row["candidate_rss_mib"], row["baseline_rss_mib"]):+.1f}%',
            row["output_check"],
        )
        lines.append("    " + ", ".join(cell(value) for value in values) + ",\n")
    lines.append(")\n")

    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("".join(lines))
    record("tbl.benchmarks", str(OUT.relative_to(PAPER)), kind="table",
           inputs=[str(SRC.relative_to(PAPER))],
           desc="Paired release and feature benchmark medians")

    with SAGE_SRC.open(newline="") as fh:
        sage_rows = list(csv.DictReader(fh))
    releases = ["Sage v0.15.0-beta.2", "Sage Plus beta.2"]
    workloads = ["conventional", "common_mods", "broad_ptm"]
    labels = {
        "conventional": "Conventional",
        "common_mods": "Common modifications",
        "broad_ptm": "Broad PTMs",
    }
    grouped = {
        (workload, release): [
            row for row in sage_rows
            if row["workload"] == workload and row["release"] == release
        ]
        for workload in workloads
        for release in releases
    }
    release_lines = [
        HEADER,
        "#table(\n",
        "  columns: 7,\n",
        "  align: (left, right, right, right, right, right, right),\n",
        "  inset: 3pt,\n",
        "  table.header(\n",
        "    " + ", ".join(cell(label, bold=True) for label in (
            "Workload", "Sage wall", "Plus wall", "Wall change", "Sage RSS", "Plus RSS", "RSS change"
        )) + ",\n",
        "  ),\n",
    ]
    for workload in workloads:
        sage_wall = median(float(row["wall_seconds"]) for row in grouped[workload, releases[0]])
        plus_wall = median(float(row["wall_seconds"]) for row in grouped[workload, releases[1]])
        sage_rss = median(float(row["peak_rss_mib"]) for row in grouped[workload, releases[0]])
        plus_rss = median(float(row["peak_rss_mib"]) for row in grouped[workload, releases[1]])
        values = (
            labels[workload],
            f"{sage_wall:.2f} s",
            f"{plus_wall:.2f} s",
            f"{percent_change(str(plus_wall), str(sage_wall)):+.1f}%",
            f"{sage_rss:,.1f} MiB",
            f"{plus_rss:,.1f} MiB",
            f"{percent_change(str(plus_rss), str(sage_rss)):+.1f}%",
        )
        release_lines.append("    " + ", ".join(cell(value) for value in values) + ",\n")
    release_lines.append(")\n")
    RELEASE_OUT.write_text("".join(release_lines))
    record("tbl.release-comparison", str(RELEASE_OUT.relative_to(PAPER)), kind="table",
           inputs=[str(SAGE_SRC.relative_to(PAPER))],
           desc="Matched workload medians for upstream Sage and Sage Plus")
    print(f"wrote {OUT.relative_to(PAPER)}  ({len(rows)} rows)")
    print(f"wrote {RELEASE_OUT.relative_to(PAPER)}  ({len(workloads)} rows)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
