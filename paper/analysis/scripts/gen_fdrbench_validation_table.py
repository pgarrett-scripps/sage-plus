#!/usr/bin/env python3
"""Write the repeated paired entrapment summary table."""

from __future__ import annotations

import csv
from pathlib import Path

from _assets import record


HERE = Path(__file__).resolve().parent
PAPER = HERE.parent.parent
SRC = HERE / "fdrbench_validation_results.csv"
OUT = PAPER / "si" / "fdrbench_validation_table.typ"
HEADER = f"// AUTO-GENERATED by scripts/{Path(__file__).name}, do not edit by hand.\n"


def cell(text: str, *, bold: bool = False) -> str:
    for character in ("\\", "[", "]", "#", "$", "*", "_", "@", "<", ">"):
        text = text.replace(character, "\\" + character)
    weight = ', weight: "bold"' if bold else ""
    return f"[#text(size: 6.7pt{weight})[{text}]]"


def main() -> int:
    with SRC.open(newline="") as handle:
        rows = list(csv.DictReader(handle))
    calibration = {
        (row["engine"], float(row["threshold"])): row
        for row in rows
        if row["analysis"] == "shuffled_calibration"
    }
    yields = {
        (row["engine"], float(row["threshold"])): row
        for row in rows
        if row["analysis"] == "matched_yield"
    }
    lines = [
        HEADER,
        "#table(\n",
        "  columns: 5,\n",
        "  align: (right, right, right, right, right),\n",
        "  inset: 3pt,\n",
        "  table.header(\n",
        "    "
        + ", ".join(
            cell(label, bold=True)
            for label in (
                "q limit",
                "Sage paired FDP",
                "Sage Plus paired FDP",
                "Sage targets",
                "Sage Plus targets",
            )
        )
        + ",\n",
        "  ),\n",
    ]
    for limit in (0.01, 0.02, 0.05, 0.10, 0.20):
        values = [f"{limit:.0%}"]
        for engine in ("Sage", "Sage Plus"):
            row = calibration[engine, limit]
            values.append(
                f'{float(row["mean"]):.1%} '
                f'[{float(row["lower"]):.1%}, {float(row["upper"]):.1%}]'
            )
        values.extend(
            f'{float(yields[engine, limit]["mean"]):.1f}'
            for engine in ("Sage", "Sage Plus")
        )
        lines.append("    " + ", ".join(cell(value) for value in values) + ",\n")
    lines.append(")\n")
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("".join(lines))
    record(
        "tbl.fdrbench-validation",
        str(OUT.relative_to(PAPER)),
        kind="table",
        inputs=[str(SRC.relative_to(PAPER))],
        desc="Repeated paired entrapment calibration and matched-FDP yield",
    )
    print(f"wrote {OUT.relative_to(PAPER)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
